"""Pack the panel atlas: every button's sprite (on), a dimmed desaturated copy (off), its four lit ring segments
(seg), and one soft white halo disc. Writes panel_atlas.png and panel_atlas.json (regions, disc radius in atlas px)."""
import json, sys
import numpy as np
from PIL import Image
CUT, OUT = sys.argv[1], sys.argv[2]
meta = json.load(open(f"{CUT}/cut.json"))
SCALE = {"attack": 0.75, "split": 0.8, "whirl": 0.8, "rally": 0.8}
W, H, PAD = 2048, 1024, 6
order = ["attack", "shield", "shoot", "rain", "dash", "split", "whirl", "rally"]
items = []
def off_of(im):
    a = np.asarray(im).astype(np.float32); l = (a[..., :3] * [0.299, 0.587, 0.114]).sum(2, keepdims=True)
    rgb = (a[..., :3] * 0.22 + l * 0.78) * 0.62 + 18
    return Image.fromarray(np.dstack([np.clip(rgb, 0, 255), a[..., 3]]).astype(np.uint8), "RGBA")
for b in order:
    k = SCALE.get(b, 1.0); m = meta[b]
    on = Image.open(f"{CUT}/{b}.png"); seg = Image.open(f"{CUT}/{b}_seg.png")
    if k != 1.0:
        n = int(round(on.size[0] * k / 2)) * 2
        # premultiplied resize, so no dark or pale fringe comes back
        def rs(im):
            a = np.asarray(im).astype(np.float32) / 255.0; a[..., :3] *= a[..., 3:4]
            r = np.asarray(Image.fromarray((a * 255).astype(np.uint8), "RGBA").resize((n, n), Image.LANCZOS)).astype(np.float32) / 255.0
            al = np.maximum(r[..., 3:4], 1e-4); r[..., :3] = np.clip(r[..., :3] / al, 0, 1)
            return Image.fromarray((r * 255).astype(np.uint8), "RGBA")
        on, seg = rs(on), rs(seg); k = n / (2.0 * m["half"])
    items.append((b, "on", on)); items.append((b, "off", off_of(on))); items.append((b, "seg", seg))
    m["_k"] = k
# the halo: a white disc with a crisp antialiased edge and his slightly brighter rim, tinted per button when drawn
n = 256; yy, xx = np.mgrid[0:n, 0:n]; d = np.hypot(xx - 127.5, yy - 127.5)
al = np.clip((122.0 - d) / 1.2, 0, 1) * (0.84 + 0.16 * np.clip((d - 116) / 4, 0, 1))
items.append(("halo", "on", Image.fromarray(np.dstack([np.full((n, n, 3), 255.0), al * 255]).astype(np.uint8), "RGBA")))
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0)); out = {}
x = y = PAD; row = 0
for b, kind, im in sorted(items, key=lambda t: -t[2].size[1]):
    w, h = im.size
    if x + w + PAD > W:
        x = PAD; y += row + PAD; row = 0
    assert y + h + PAD <= H, "atlas full"
    atlas.paste(im, (x, y)); row = max(row, h)
    e = out.setdefault(b, {}); e[kind] = [x, y, w, h]
    x += w + PAD
for b in order:
    m = meta[b]; k = m["_k"]
    out[b].update({"r": round(m["r"] * k, 3), "half": round(m["half"] * k, 3),
                   "off_x": round((m["cx"] - m["px"][0]) * k, 3), "off_y": round((m["cy"] - m["px"][1]) * k, 3),
                   "halo": [c / 255.0 for c in m["halo_rgb"]], "interim": "from" in m})
out["halo"]["r"] = 122.0
atlas.save(f"{OUT}/panel_atlas.png", optimize=True)
json.dump(out, open(f"{OUT}/panel_atlas.json", "w"), indent=1)
print("atlas", atlas.size, "used rows to y =", y + row)

# the same table as a GDScript constant (no file read at run time, nothing for the export filter to miss)
def gd(v):
    if isinstance(v, dict): return "{" + ", ".join(f'"{k}": {gd(x)}' for k, x in v.items()) + "}"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, list): return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, float): return repr(round(v, 4))
    return repr(v)
with open(f"{OUT}/panel_atlas.gd", "w") as f:
    f.write("## Generated by the panel track's atlas.py from Wale's sheet 59328 (do not edit by hand): where each button's\n"
            "## sprites sit in panel_atlas.png. on / off / seg: [x, y, w, h]; r: the disc's radius in atlas px; half: half the\n"
            "## sprite's side; off_x, off_y: the disc's centre from the sprite's centre; halo: the halo's colour on his sheet.\n"
            "const A: Dictionary = {\n")
    for k, v in out.items():
        f.write(f'\t"{k}": {gd(v)},\n')
    f.write("}\n")
